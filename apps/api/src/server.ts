import { existsSync } from 'node:fs';
import { loadEnvFile } from 'node:process';
import { fileURLToPath } from 'node:url';

import { createDatabase } from '@astral-atlas/database';

import { buildApp } from './app.js';
import { parseApiConfig } from './config.js';

import { AnalysisEventHub, connectAnalysisQueueEvents } from './queues/analysis-event-hub.js';

import { createAnalysisQueueEvents } from './queues/analysis-events.js';

import { createAnalysisQueue } from './queues/analysis-queue.js';

import { createRedisClient } from './redis.js';

const rootEnvPath = fileURLToPath(new URL('../../../.env', import.meta.url));

if (existsSync(rootEnvPath)) {
  loadEnvFile(rootEnvPath);
}

const config = parseApiConfig(process.env);

const database = createDatabase(config.databaseUrl);

const redis = createRedisClient(config.redis);

/*
 * Producer-side BullMQ queue.
 *
 * The API uses this queue to place
 * repository-analysis jobs into Redis.
 */
const analysisQueue = createAnalysisQueue(redis);

/*
 * QueueEvents listens for global BullMQ events
 * generated by workers:
 *
 * progress
 * completed
 * failed
 *
 * It uses its own Redis connection internally.
 */
const analysisQueueEvents = createAnalysisQueueEvents(config.redis);

/*
 * In-memory event distribution layer.
 *
 * QueueEvents
 *      ↓
 * AnalysisEventHub
 *      ↓
 * SSE clients
 */
const analysisEventHub = new AnalysisEventHub();

/*
 * Connect BullMQ global events to our
 * application-level event hub.
 */
const disconnectAnalysisQueueEvents = connectAnalysisQueueEvents(
  analysisQueueEvents,
  analysisEventHub,
);

const app = await buildApp({
  config,

  /*
   * Pass the SAME event hub instance into
   * Fastify.
   *
   * QueueEvents publishes into this hub,
   * while the SSE route subscribes to it.
   */
  analysisEventHub,

  readinessProbe: async () => {
    const [databaseResult, redisResult] = await Promise.allSettled([database.ping(), redis.ping()]);

    return {
      database: databaseResult.status === 'fulfilled' ? 'up' : 'down',

      redis: redisResult.status === 'fulfilled' ? 'up' : 'down',
    };
  },

  closeResources: async () => {
    /*
     * First stop forwarding QueueEvents
     * into the in-memory hub.
     */
    disconnectAnalysisQueueEvents();

    /*
     * Close BullMQ resources before
     * closing Redis.
     *
     * analysisQueueEvents owns its own
     * Redis connection.
     *
     * analysisQueue uses the API Redis
     * connection created above.
     */
    await Promise.allSettled([analysisQueueEvents.close(), analysisQueue.close()]);

    /*
     * PostgreSQL and the API Redis
     * connection can now shut down.
     */
    await Promise.allSettled([database.close(), redis.quit()]);
  },
});

/*
 * QueueEvents is a long-running EventEmitter.
 *
 * Always attach an error listener so Redis /
 * BullMQ connection problems are logged rather
 * than becoming unhandled EventEmitter errors.
 */
analysisQueueEvents.on('error', (error) => {
  app.log.error(
    {
      err: error,
    },
    'BullMQ QueueEvents error',
  );
});

let shuttingDown = false;

async function shutdown(signal: NodeJS.Signals): Promise<void> {
  if (shuttingDown) {
    return;
  }

  shuttingDown = true;

  app.log.info(
    {
      signal,
    },
    'Shutdown signal received',
  );

  try {
    /*
     * app.close() triggers the onClose hook,
     * which runs closeResources().
     */
    await app.close();

    app.log.info('API shutdown completed');

    process.exitCode = 0;
  } catch (error: unknown) {
    app.log.error(
      {
        err: error,
      },
      'API shutdown failed',
    );

    process.exitCode = 1;
  }
}

process.once('SIGINT', () => {
  void shutdown('SIGINT');
});

process.once('SIGTERM', () => {
  void shutdown('SIGTERM');
});

try {
  /*
   * Make sure QueueEvents is connected before
   * accepting HTTP traffic.
   *
   * This avoids missing early analysis events.
   */
  await analysisQueueEvents.waitUntilReady();

  await app.listen({
    host: config.host,

    port: config.port,
  });
} catch (error: unknown) {
  app.log.error(
    {
      err: error,
    },
    'API failed to start',
  );

  /*
   * app.close() also runs closeResources(),
   * cleaning up:
   *
   * QueueEvents
   * Queue
   * PostgreSQL
   * Redis
   */
  await app.close().catch(() => undefined);

  process.exitCode = 1;
}
